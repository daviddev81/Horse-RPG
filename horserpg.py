SAVE_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "savegame.json")


def execute_save():
  save_data = {
    "version": 1,
    "wallet": int(player_wallet),
    "horse": look if "look" in globals() else "none",
    "mountains": ms if "ms" in globals() else "none",
    "stage": game_stage,
  }
  with open(SAVE_FILE, "w") as file:
    json.dump(save_data, file, indent=2)
  print(f"\n{GREEN_BACK}[GAME SAVED]{RESET} Progress secured in {SAVE_FILE}!")


def load_save():
  global player_wallet, look, ms, game_stage

  if not os.path.exists(SAVE_FILE):
    return False

  try:
    with open(SAVE_FILE) as file:
      save_data = json.load(file)
    player_wallet = str(int(save_data["wallet"]))
    look = save_data.get("horse", "none")
    ms = save_data.get("mountains", "none")
    game_stage = save_data.get("stage")
    if game_stage is None:
      if ms in ("mc", "oc", "or"):
        game_stage = "cave"
      elif look in ("joey", "hammer", "oldey"):
        game_stage = "mountain_selection"
      else:
        game_stage = "opening"
  except (OSError, ValueError, TypeError, json.JSONDecodeError, KeyError):
    print(f"{RED}Save file could not be loaded. Starting a new game.{RESET}")
    return False

  print(f"{GREEN_BACK}[SAVE LOADED]{RESET} Progress restored from {SAVE_FILE}.")
  return True

def read_command(question_message):
    while True:
        response = input(question_message).lower().strip()
        if response == "save":
            execute_save()
            print("Resuming game...")
            continue
        if response == "load":
          if load_save():
            print("Resuming game...")
          continue
        else:
            return response

